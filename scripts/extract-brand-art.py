#!/usr/bin/env python3
"""Extract the official crest and mountain artwork from the brand guideline PDF.

Usage: python3 scripts/extract-brand-art.py <p1.svg> <outdir>
where p1.svg comes from `pdftocairo -svg -f 1 -l 1 BRAND_GUIDELINE_FINAL.pdf p1.svg`.

Writes outdir/crestData.ts (classified path data for the crest) and outdir/peakData.ts
(path data for the large mountain on the cover). Run with outdir=components/brand.
"""
import json
import re
import sys

src, out = sys.argv[1], sys.argv[2]
s = open(src).read()
body = s[s.find("</defs>") + 7 :]

PATH = re.compile(r'<path fill-rule="nonzero" fill="rgb\(([^)]+)\)" fill-opacity="1" d="([^"]+)"')


def bbox(d):
    n = [float(x) for x in re.findall(r"-?\d+\.?\d*", d)]
    return min(n[0::2]), max(n[0::2]), min(n[1::2]), max(n[1::2])


def rnd(d, ox=0.0, oy=0.0):
    # shift to origin and round to 1 decimal; path uses only absolute M/L/C/Z commands
    toks = re.findall(r"[MLCZ]|-?\d+\.?\d*", d)
    res, idx, cmd = [], 0, None
    for t in toks:
        if t in "MLCZ":
            res.append(t)
            idx = 0
        else:
            v = float(t) - (ox if idx % 2 == 0 else oy)
            idx += 1
            res.append(("%.1f" % v).rstrip("0").rstrip("."))
    return " ".join(res).replace(" Z", "Z")


crest, peak = {"shell": [], "ink": [], "book": [], "label": []}, []
for col, d in PATH.findall(body):
    x0, x1, y0, y1 = bbox(d)
    r, g, b = [float(c.strip("%")) for c in col.split(",")]
    in_logo = x0 > 55 and x1 < 370 and y0 > 60 and y1 < 460
    if in_logo:
        if abs(r - 11.76) < 0.5 and abs(g - 29.4) < 0.5:
            crest["shell"].append(d)
        elif r > 90:
            crest["label"].append(d)
        elif abs(r - 53.3) < 0.5:
            crest["book"].append(d)
        elif r < 8:
            crest["ink"].append(d)
        # anything else (stray anti-aliasing fragment) is dropped
    elif x1 > 500 and not (x1 < 640 and y0 > 500):
        peak.append(d)

ox, oy = 64.4, 79.3
# outer boundary of the shield (largest sub-path of the shell) becomes the face fill
shell = crest["shell"][0]
subs = ["M" + p for p in shell.split("M") if p.strip()]
face = max(subs, key=lambda p: (lambda b: (b[1] - b[0]) * (b[3] - b[2]))(bbox(p)))
data = {
    "viewBox": "0 0 %.1f %.1f" % (352.8 - ox + 0.6, 446.4 - oy + 0.6),
    "face": rnd(face, ox, oy),
    "shell": [rnd(p, ox, oy) for p in crest["shell"]],
    "ink": [rnd(p, ox, oy) for p in crest["ink"]],
    "book": [rnd(p, ox, oy) for p in crest["book"]],
    "label": [rnd(p, ox, oy) for p in crest["label"]],
}
peak_data = {"viewBox": "534 0 307.4 594.6", "paths": [rnd(p) for p in peak]}
header = "// Generated by scripts/extract-brand-art.py from the official brand guideline PDF. Do not edit.\n"
open(out + "/crestData.ts", "w").write(header + "export const CREST = " + json.dumps(data, indent=2) + " as const;\n")
open(out + "/peakData.ts", "w").write(header + "export const PEAK = " + json.dumps(peak_data, indent=2) + " as const;\n")
print({k: (len(v) if isinstance(v, list) else len(v)) for k, v in data.items()}, "peak paths:", len(peak))

# App icon: the green crest on a navy square (guideline p.11: green logo for navy backgrounds)
vb = data["viewBox"].split()
w, h = float(vb[2]), float(vb[3])
scale, size = 0.74, 100
cw, ch = size * scale * w / h, size * scale
tx, ty = (size - cw) / 2, (size - ch) / 2
g = lambda arr, fill: '<g fill="%s">%s</g>' % (fill, "".join('<path d="%s"/>' % d for d in arr))
icon = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" rx="18" fill="#121e34"/>'
    '<g transform="translate(%.2f %.2f) scale(%.4f)">%s%s%s%s</g></svg>'
    % (tx, ty, ch / h, g(data["shell"], "#88b03f"), g(data["ink"], "#88b03f"), g(data["book"], "#88b03f"), g(data["label"], "#121e34"))
)
import os
open(os.path.join(os.path.dirname(os.path.abspath(out)), "..", "app", "icon.svg"), "w").write(icon)
